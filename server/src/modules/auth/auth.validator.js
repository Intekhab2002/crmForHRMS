/**
 * ============================================================================
 * Authentication Validators
 * ============================================================================
 *
 * Provides Zod schemas for authentication-related HTTP input.
 *
 * Responsibilities
 * ----------------------------------------------------------------------------
 * • Validate authentication request payloads.
 * • Normalize safe textual input.
 * • Reject malformed request data.
 *
 * This module does NOT:
 * • Query the database.
 * • Authenticate users.
 * • Verify passwords.
 * • Verify JWTs.
 * • Manage sessions.
 * • Perform authorization.
 *
 * ============================================================================
 */

import { z } from "zod";

/**
 * ============================================================================
 * Shared Schemas
 * ============================================================================
 */

/**
 * Login identifier schema.
 *
 * The identifier may represent either a username or an email address.
 * The repository/service layer determines the actual identity type.
 */
const identifierSchema = z
    .string({
        error:
            "Username or email is required.",
    })
    .trim()
    .min(1, {
        error:
            "Username or email is required.",
    })
    .max(255, {
        error:
            "Username or email must not exceed 255 characters.",
    });

/**
 * Password schema.
 *
 * Password strength requirements are intentionally not enforced here for
 * login because an existing user's password may have been created under an
 * older policy. Login only requires a non-empty password.
 */
const loginPasswordSchema = z
    .string({
        error: "Password is required.",
    })
    .min(1, {
        error: "Password is required.",
    })
    .max(128, {
        error:
            "Password must not exceed 128 characters.",
    });

/**
 * Refresh token schema.
 *
 * Refresh tokens are opaque authentication credentials from the validator's
 * perspective. Their cryptographic validity is checked by the token/session
 * services.
 */
const refreshTokenSchema = z
    .string({
        error: "Refresh token is required.",
    })
    .trim()
    .min(1, {
        error: "Refresh token is required.",
    })
    .max(4096, {
        error:
            "Refresh token exceeds the maximum allowed length.",
    });

