/**
 * ============================================================================
 * Request Schemas
 * ============================================================================
 */

/**
 * Login request schema.
 *
 * Expected payload:
 *
 * {
 *     identifier: string,
 *     password: string
 * }
 */
const loginSchema = z
    .object({
        identifier: identifierSchema,

        password: loginPasswordSchema,
    })
    .strict();

/**
 * Refresh-token request schema.
 *
 * Expected payload:
 *
 * {
 *     refreshToken: string
 * }
 */
const refreshSchema = z
    .object({
        refreshToken: refreshTokenSchema,
    })
    .strict();

