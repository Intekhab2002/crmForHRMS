/**
 * ============================================================================
 * Authentication Constants
 * ============================================================================
 *
 * Authentication-domain constants and security policies.
 *
 * Responsibilities
 * ----------------------------------------------------------------------------
 * • Define authentication-specific token types.
 * • Define authentication-specific account states.
 * • Define login lockout policy.
 * • Define authentication error/success machine codes.
 * • Define authentication session policy.
 *
 * This module intentionally does NOT contain:
 * ----------------------------------------------------------------------------
 * • Generic HTTP status codes.
 * • Generic application messages.
 * • JWT implementation logic.
 * • Password hashing logic.
 * • Database queries.
 * • Express logic.
 *
 * Generic application constants remain centralized in:
 *
 *     src/constants/
 *
 * Authentication-specific constants belong here because they are part of the
 * authentication bounded context.
 *
 * ============================================================================
 */

/**
 * ============================================================================
 * Authentication Token Types
 * ============================================================================
 *
 * These values correspond to the `type` claim generated by auth.tokens.js.
 */
export const AUTH_TOKEN_TYPES = Object.freeze({
    ACCESS: "access",
    REFRESH: "refresh",
});

/**
 * ============================================================================
 * Authentication Account Statuses
 * ============================================================================
 *
 * These values correspond to the `users.status` database column.
 *
 * The database is the final authority for persisted status. These constants
 * prevent authentication services from scattering status strings throughout
 * the codebase.
 */
export const AUTH_ACCOUNT_STATUS = Object.freeze({
    PENDING: "pending",
    ACTIVE: "active",
    INACTIVE: "inactive",
    SUSPENDED: "suspended",
    LOCKED: "locked",
});

/**
 * ============================================================================
 * Login Policy
 * ============================================================================
 *
 * Account lockout policy is deliberately kept separate from the repository.
 *
 * The repository persists the result of this policy.
 *
 * Current policy:
 *
 *     Maximum failed attempts = 5
 *     Lock duration            = 15 minutes
 *
 * These are authentication policy defaults, not database configuration.
 *
 * If these values later become tenant-configurable, the policy should move to
 * the appropriate configuration/domain layer rather than being duplicated.
 */
export const AUTH_LOGIN_POLICY = Object.freeze({
    MAX_FAILED_ATTEMPTS: 5,

    LOCK_DURATION_MINUTES: 15,
});

/**
 * ============================================================================
 * Authentication Session Policy
 * ============================================================================
 *
 * The project requires one active authentication session per user.
 *
 * Historical sessions remain persisted for audit/security purposes.
 */
export const AUTH_SESSION_POLICY = Object.freeze({
    SINGLE_ACTIVE_SESSION: true,

    ROTATE_REFRESH_TOKEN: true,
});

